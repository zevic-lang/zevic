/* Generates packages/Zevic/src/Convert.zev: the conversions that can fail and therefore return a Result.
 *
 *   <From>To<To>(x)     integer -> narrower or differently signed integer, e.g. I64ToI32
 *   StringTo<Type>(s)   text -> number, e.g. StringToI32, StringToF64
 *
 * The compiler calls these when it sees `x.ToI32()` and `s.ToI32()`.
 * The text-to-number part is written by hand in tools/convert_text.zev.in.
 *
 *   cc tools/gen_convert.c -o build/gen_convert
 *   build/gen_convert tools/convert_text.zev.in > packages/Zevic/src/Convert.zev
 */
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct {
    const char *name;
    bool is_signed;
    int bits;
} Int;

static const Int INTS[] = {{"I8", true, 8},  {"I16", true, 16}, {"I32", true, 32}, {"I64", true, 64},
                           {"U8", false, 8}, {"U16", false, 16}, {"U32", false, 32}, {"U64", false, 64}};
#define N_INTS 8

/* the range as decimal text, because U64 does not fit in a long long */
static const char *range_lo(const Int *t, char *buf) {
    if (!t->is_signed) return "0";
    switch (t->bits) {
    case 8: return "-128";
    case 16: return "-32768";
    case 32: return "-2147483648";
    default: snprintf(buf, 32, "-9223372036854775808"); return buf;
    }
}

static const char *range_hi(const Int *t) {
    if (t->is_signed) {
        switch (t->bits) {
        case 8: return "127";
        case 16: return "32767";
        case 32: return "2147483647";
        default: return "9223372036854775807";
        }
    }
    switch (t->bits) {
    case 8: return "255";
    case 16: return "65535";
    case 32: return "4294967295";
    default: return "18446744073709551615";
    }
}

/* Does every value of `from` fit in `to`? */
static bool fits(const Int *from, const Int *to) {
    if (from->is_signed == to->is_signed) return to->bits >= from->bits;
    if (!from->is_signed && to->is_signed) return to->bits > from->bits;
    return false; /* signed -> unsigned: negative values do not fit */
}

int main(int argc, char **argv) {
    if (argc != 2) {
        fprintf(stderr, "usage: gen_convert tools/convert_text.zev.in\n");
        return 2;
    }
    FILE *tf = fopen(argv[1], "rb");
    if (!tf) {
        fprintf(stderr, "cannot read %s\n", argv[1]);
        return 1;
    }
    puts("module Zevic.Convert");
    puts("");
    puts("// GENERATED by tools/gen_convert.c - do not edit by hand.");
    puts("// Conversions that can fail. The compiler calls them for `x.ToI32()` (integers) and `s.ToI32()` (strings).");
    puts("");
    char buf[32];
    for (int a = 0; a < N_INTS; a++) {
        for (int b = 0; b < N_INTS; b++) {
            const Int *f = &INTS[a], *t = &INTS[b];
            if (a == b || fits(f, t)) continue;
            printf("fn %sTo%s(x: %s) -> Result<%s, Error> {\n", f->name, t->name, f->name, t->name);
            if (!strcmp(f->name, "U64")) {
                printf("    if (x > %s) {\n", range_hi(t));
            } else if (!strcmp(t->name, "U64")) {
                puts("    let v: I64 = x.ToI64()");
                puts("    if (v < 0) {");
            } else {
                puts("    let v: I64 = x.ToI64()");
                printf("    if (v < %s || v > %s) {\n", range_lo(t, buf), range_hi(t));
            }
            printf("        return Err(Error.New(ErrorKind.OutOfRange, \"${x} does not fit in %s\"))\n", t->name);
            puts("    }");
            printf("    Ok(x.To%sWrap())\n", t->name);
            puts("}");
            puts("");
        }
    }
    int c;
    while ((c = fgetc(tf)) != EOF) putchar(c);
    fclose(tf);
    /* text -> the other integer types go through I64 and the range check above */
    for (int a = 0; a < N_INTS; a++) {
        const char *t = INTS[a].name;
        if (!strcmp(t, "I64") || !strcmp(t, "U64")) continue;
        printf("fn StringTo%s(s: String) -> Result<%s, Error> {\n", t, t);
        puts("    let v: I64 = StringToI64(s)?");
        printf("    I64To%s(v)\n", t);
        puts("}");
        puts("");
    }
    /* Char <-> U32: a Char is a Unicode scalar value (not a surrogate, at most U+10FFFF) */
    puts("fn U32ToChar(x: U32) -> Result<Char, Error> {");
    puts("    if (x > 1114111 || (x >= 55296 && x <= 57343)) {");
    puts("        return Err(Error.New(ErrorKind.OutOfRange, \"${x} is not a Unicode scalar value\"))");
    puts("    }");
    puts("    Ok(x.ToCharUnchecked())");
    puts("}");
    return 0;
}
