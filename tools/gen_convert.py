#!/usr/bin/env python3
"""Generate packages/Zevic/src/Convert.zev: the conversions that can fail and therefore return a Result.

  <From>To<To>(x)     integer -> narrower or differently signed integer, e.g. I64ToI32
  StringTo<Type>(s)   text -> number, e.g. StringToI32, StringToF64

The compiler calls these when it sees `x.ToI32()` and `s.ToI32()`.
Run:  python3 tools/gen_convert.py > packages/Zevic/src/Convert.zev
"""

INTS = [("I8", True, 8), ("I16", True, 16), ("I32", True, 32), ("I64", True, 64),
        ("U8", False, 8), ("U16", False, 16), ("U32", False, 32), ("U64", False, 64)]


def rng(signed, bits):
    return (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if signed else (0, (1 << bits) - 1)


def fits(frm, to):
    fs, fb = frm[1], frm[2]
    ts, tb = to[1], to[2]
    flo, fhi = rng(fs, fb)
    tlo, thi = rng(ts, tb)
    return tlo <= flo and fhi <= thi


def lit(v, ty):
    # a literal in the type of the variable it is compared with
    return str(v)


out = []
w = out.append
w("module Zevic.Convert")
w("")
w("// GENERATED by tools/gen_convert.py - do not edit by hand.")
w("// Conversions that can fail. The compiler calls them for `x.ToI32()` (integers) and `s.ToI32()` (strings).")
w("")

for frm in INTS:
    for to in INTS:
        if frm[0] == to[0] or fits(frm, to):
            continue
        fname, tname = frm[0], to[0]
        tlo, thi = rng(to[1], to[2])
        w(f"fn {fname}To{tname}(x: {fname}) -> Result<{tname}, Error> {{")
        if fname == "U64":
            w(f"    if (x > {thi}) {{")
        elif tname == "U64":
            w("    let v: I64 = x.ToI64()")
            w("    if (v < 0) {")
        else:
            w("    let v: I64 = x.ToI64()")
            w(f"    if (v < {tlo} || v > {thi}) {{")
        w(f'        return Err(Error.New(ErrorKind.OutOfRange, "${{x}} does not fit in {tname}"))')
        w("    }")
        w(f"    Ok(x.To{tname}Wrap())")
        w("}")
        w("")

w('''// ---- text to numbers ----

extern "zevic" {
    fn zevic_f64_valid(s: String) -> I32
    fn zevic_f64_parse(s: String) -> F64
}

fn badNumber(s: String, why: String) -> Error {
    Error.New(ErrorKind.InvalidFormat, "cannot read \\"${s}\\" as a number: ${why}")
}

fn StringToI64(s: String) -> Result<I64, Error> {
    let n: I64 = s.Len()
    if (n == 0) {
        return Err(badNumber(s, "the text is empty"))
    }
    mut i: I64 = 0
    mut neg: Bool = false
    let first: U8 = s.ByteAt(0)
    if (first == b'-') {
        neg = true
        i = 1
    } else if (first == b'+') {
        i = 1
    }
    if (i == n) {
        return Err(badNumber(s, "there are no digits"))
    }
    let limit: U64 = if (neg) { 9223372036854775808 } else { 9223372036854775807 }
    mut acc: U64 = 0
    while (i < n) {
        let c: U8 = s.ByteAt(i)
        if (c < b'0' || c > b'9') {
            return Err(badNumber(s, "found a character that is not a digit"))
        }
        let d: U64 = (c - b'0').ToU64()
        if (acc > (limit - d) / 10) {
            return Err(Error.New(ErrorKind.OutOfRange, "\\"${s}\\" does not fit in I64"))
        }
        acc = acc * 10 + d
        i += 1
    }
    if (neg) {
        Ok(0_I64.WrapSub(acc.ToI64Wrap()))
    } else {
        Ok(acc.ToI64Wrap())
    }
}

fn StringToU64(s: String) -> Result<U64, Error> {
    let n: I64 = s.Len()
    if (n == 0) {
        return Err(badNumber(s, "the text is empty"))
    }
    mut i: I64 = 0
    if (s.ByteAt(0) == b'+') {
        i = 1
    }
    if (i == n) {
        return Err(badNumber(s, "there are no digits"))
    }
    mut acc: U64 = 0
    while (i < n) {
        let c: U8 = s.ByteAt(i)
        if (c < b'0' || c > b'9') {
            if (i == 0 && c == b'-') {
                return Err(Error.New(ErrorKind.OutOfRange, "\\"${s}\\" is negative and does not fit in U64"))
            }
            return Err(badNumber(s, "found a character that is not a digit"))
        }
        let d: U64 = (c - b'0').ToU64()
        if (acc > (18446744073709551615 - d) / 10) {
            return Err(Error.New(ErrorKind.OutOfRange, "\\"${s}\\" does not fit in U64"))
        }
        acc = acc * 10 + d
        i += 1
    }
    Ok(acc)
}

fn StringToF64(s: String) -> Result<F64, Error> {
    if (zevic_f64_valid(s) == 0) {
        return Err(badNumber(s, "the format is not a decimal number"))
    }
    Ok(zevic_f64_parse(s))
}

fn StringToF32(s: String) -> Result<F32, Error> {
    let v: F64 = StringToF64(s)?
    Ok(v.ToF32())
}
''')

# text -> the other integer types go through I64 (or U64) and the range check above
for to in INTS:
    t = to[0]
    if t in ("I64", "U64"):
        continue
    w(f"fn StringTo{t}(s: String) -> Result<{t}, Error> {{")
    w("    let v: I64 = StringToI64(s)?")
    w(f"    I64To{t}(v)")
    w("}")
    w("")

# Char <-> U32: a Char is a Unicode scalar value (not a surrogate, at most U+10FFFF)
w("fn U32ToChar(x: U32) -> Result<Char, Error> {")
w("    if (x > 1114111 || (x >= 55296 && x <= 57343)) {")
w('        return Err(Error.New(ErrorKind.OutOfRange, "${x} is not a Unicode scalar value"))')
w("    }")
w("    Ok(x.ToCharUnchecked())")
w("}")
w("")

print("\n".join(out))
